"use strict";

const CACHE_NAME = "orbit-pwa-v1.0.1";
const APP_SHELL = [
  "./demo.html",
  "./avatar-companion.js",
  "./icon-192.png",
  "./icon-512.png",
  "./orbit-spritesheet-pink.png",
  "./orbit-actions-emotions-pink.png",
  "./orbit-actions-acrobatics-pink.png",
  "./orbit-actions-entertainment-pink.png",
  "./orbit-actions-love-pink.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith("orbit-pwa-") && key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put("./demo.html", copy));
          return response;
        })
        .catch(() => caches.match("./demo.html"))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request).then((response) => {
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
      }
      return response;
    }))
  );
});
